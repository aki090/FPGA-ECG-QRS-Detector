"""Prepare simulation inputs: FIR coefficients (.vh), ECG + noise ROM files (.hex), reference beats."""
import numpy as np, wfdb, sys, os
sys.path.insert(0,'python')
import noise
from scipy.signal import firwin
N=int(sys.argv[1]) if len(sys.argv)>1 else 36000
LO,HI,TAPS=5,20,41
h=firwin(TAPS,[LO,HI],pass_zero=False,fs=360,window='hamming'); h=h/np.max(np.abs(np.fft.rfft(h,4096)))
hq=[int(round(v*4096)) for v in h]
with open('rtl/fir_coeffs.vh','w') as f:
    f.write('// Auto-generated by python/prep_sim.py : %d-tap Hamming FIR band-pass %d-%d Hz, fs=360 Hz, Q12\n'%(TAPS,LO,HI))
    f.write('localparam N_TAPS = %d;\nfunction signed [15:0] fir_coef;\n  input integer k;\n  begin\n    case (k)\n'%TAPS)
    for k,v in enumerate(hq): f.write("      %d: fir_coef = %s16'sd%d;\n"%(k,'-' if v<0 else '',abs(v)))
    f.write("      default: fir_coef = 16'sd0;\n    endcase\n  end\nendfunction\n")
np.save('python/fir_q12.npy',np.array(hq))
rec=wfdb.rdrecord('data/100',physical=False); ann=wfdb.rdann('data/100','atr')
x=rec.d_signal[:,0].astype(np.int64)-1024; x=x[:N]
assert len(x)==N and x.min()>=-2048 and x.max()<=2047
ref=[int(s) for s,c in zip(ann.sample,ann.symbol) if c in set("NLRBAaJSVrFejnE/fQ") and s<N]
nz=noise.make_noise(N,seed=7); nz=nz/np.std(nz)*(2.0*np.std(x-x.mean()))
nz=np.clip(np.round(nz),-2047,2047).astype(np.int64)
w=lambda a:'\n'.join('%03x'%(int(v)&0xFFF) for v in a)+'\n'
open('sim/ecg.hex','w').write(w(x)); open('sim/noise.hex','w').write(w(nz))
np.save('sim/ecg.npy',x); np.save('sim/noise.npy',nz)
open('data/ref_beats.txt','w').write('\n'.join(map(str,ref))+'\n')
print('N=%d samples (%.0f s), %d reference beats, ECG std %.1f ADC units'%(N,N/360,len(ref),np.std(x)))
for k in range(8):
    s=(nz*k)>>3
    print('  k=%d  noise std %6.1f  SNR %s dB'%(k,np.std(s),'inf' if k==0 else '%.1f'%(20*np.log10(np.std(x-x.mean())/np.std(s)))))
